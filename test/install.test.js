// *********************************************************************************************** //
// install.test                                                                                    //
// Check install.html offers every bookmarklet, and that what it offers is what test-bm.js ran.     //
// *********************************************************************************************** //
// Run with node --test test/install.test.js, which npm test does after gallery.test.js. The file is
// named rather than discovered, for the reason the other test files here are: node --test treats
// every .js file under a folder called test as a test file, and test/fixtures/bookmarklets holds
// fourteen that are bookmarklets.
//
// install.html is generated by make-install-page.js and committed, because GitHub Pages runs no
// build for this repository. A generated file that is committed goes stale the first time anyone
// forgets to regenerate it, and nothing about a page on a site says when it was last written - so
// the first reading here is that the committed page is what the generator writes now. That is the
// whole reason this file exists before anything it asserts about the page's markup.
//
// The second reading is the one the page is for. Each row carries an href a reader drags onto the
// bookmarks bar, and a browser percent-decodes that href before it runs what is left. What has to
// come out the other side is the join test-bm.js checks - every line of the file with nothing
// between them - character for character, because that is the code a verdict was given on. A page
// that handed out anything else would be installing something nothing ever ran, and a reader would
// have no way of telling.
//
// The page is read in a browser rather than as text for the rest, since what is in question is what
// a reader meets: the rows as a table reads them, the stacking the narrow layout does instead of
// scrolling sideways, and whether a link taken off the page runs when it is clicked.

var test = require("node:test");
var assert = require("node:assert");
var fs = require("node:fs");
var path = require("node:path");
var vm = require("node:vm");
var playwright = require("playwright");

var maker = require("../make-install-page.js");

var root = path.resolve(__dirname, "..");
var jsDir = path.join(root, "JSFormatted");
var installFile = path.join(root, "install.html");
var origin = "https://fixtures.test";

// Three widths. The table is laid out as a table at the first two and as a stack of labelled blocks
// at the third, and those are different readings of the same markup. 761px is here because it is the
// narrowest width at which the table is still a table - one pixel above the breakpoint - which is
// where a column would overflow if any of them ever did.
var WIDE = { width: 1280, height: 900 };
var TIGHT = { width: 761, height: 900 };
var NARROW = { width: 400, height: 900 };
var WIDTHS = [WIDE, TIGHT, NARROW];

// The bookmarklet whose link is clicked, and the element it puts on the page. It is here because it
// works on any page, says so by adding one element, and takes the same element away when it runs
// again - so one click proves the path from the href on the page to code running in the browser.
var CLICKED = "dom_Clutter_ClickToHide";
var CLICKED_ADDS = "#clutterClickToHide--__-unlikely_-_name-__--clutterClickToHide";

function names() {
 return fs.readdirSync(jsDir).filter(function (f) { return /\.js$/i.test(f); })
  .map(function (f) { return f.replace(/\.js$/i, ""); }).sort();
}

// The file as a bookmark's address field joins it: the line breaks gone and nothing in their place.
function joinOf(name) {
 var source = fs.readFileSync(path.join(jsDir, name + ".js"), "utf8");
 return source.split(/\r?\n/).join("").replace(/^\s*javascript:/i, "");
}

// ----------------------------------------------------------------------------------------------- //
// Reading the page
// ----------------------------------------------------------------------------------------------- //

// The repository root, served from the same fake origin test-bm.js uses, so the page's own links to
// the gallery and to the favicon resolve the way they do on the site. A path that climbs out of the
// repository is a 404 the page sees.
async function serveRoot(page) {
 await page.route(origin + "/**", async function (route) {
  var asked = decodeURIComponent(new URL(route.request().url()).pathname).replace(/^\/+/, "");
  var file = path.resolve(root, asked || "index.html");
  if (file.indexOf(root) !== 0 || !fs.existsSync(file) || fs.statSync(file).isDirectory()) {
   var index = path.join(file, "index.html");
   if (fs.existsSync(index)) { file = index; } else {
    return route.fulfill({ status: 404, contentType: "text/plain", body: "not here" })
     .catch(function () { });
   }
  }
  var ext = path.extname(file).toLowerCase();
  var type = ext === ".html" ? "text/html; charset=utf-8"
   : ext === ".png" ? "image/png"
   : ext === ".js" ? "text/javascript; charset=utf-8"
   : "application/octet-stream";
  return route.fulfill({ status: 200, contentType: type, body: fs.readFileSync(file) })
   .catch(function () { });
 });
}

// What the page says, read as a reader's browser lays it out.
function readPage() {
 function words(el) { return (el.textContent || "").replace(/\s+/g, " ").trim(); }
 var rows = Array.prototype.slice.call(document.querySelectorAll("tbody tr")).map(function (tr) {
  var head = tr.querySelector("th[scope='row']");
  var cells = Array.prototype.slice.call(tr.querySelectorAll("td"));
  var drag = tr.querySelector("a.drag");
  var byLabel = {};
  cells.forEach(function (td) { byLabel[td.getAttribute("data-label")] = words(td); });
  return {
   file: words(head.querySelector("code.file")),
   title: words(head).replace(words(head.querySelector("code.file")), "").trim(),
   description: byLabel["What it does"] || "",
   status: words(tr.querySelector(".state")),
   statusKind: (tr.querySelector(".state") || { className: "" }).className.replace("state", "").trim(),
   href: drag ? drag.getAttribute("href") : null,
   dragText: drag ? words(drag) : null,
   noDrag: words(tr.querySelector(".noDrag") || document.createElement("i")),
   links: Array.prototype.slice.call(tr.querySelectorAll("td[data-label='More'] a"))
    .map(function (a) { return { text: words(a), href: a.getAttribute("href") }; })
  };
 });
 return {
  title: document.title,
  headings: Array.prototype.slice.call(document.querySelectorAll("h1, h2, h3, h4, h5, h6"))
   .map(function (h) { return { level: +h.tagName.slice(1), text: words(h) }; }),
  tables: Array.prototype.slice.call(document.querySelectorAll("table")).map(function (table) {
   var region = table.closest(".rows");
   return {
    caption: words(table.querySelector("caption")),
    columns: Array.prototype.slice.call(table.querySelectorAll("thead th"))
     .map(function (th) { return { text: words(th), scope: th.getAttribute("scope") }; }),
    rows: table.querySelectorAll("tbody tr").length,
    region: region ? { role: region.getAttribute("role"), tabindex: region.getAttribute("tabindex"),
     label: region.getAttribute("aria-label") } : null
   };
  }),
  rows: rows,
  // What the layout is doing, which is what the two viewports are read at.
  laidOut: (function () {
   var head = document.querySelector("thead");
   var row = document.querySelector("tbody tr");
   var cell = document.querySelector("tbody td");
   return {
    headShown: head ? head.getBoundingClientRect().width > 2 : null,
    rowDisplay: row ? getComputedStyle(row).display : null,
    cellDisplay: cell ? getComputedStyle(cell).display : null,
    cellLabel: cell ? getComputedStyle(cell, "::before").content : null,
    boxesScroll: Array.prototype.slice.call(document.querySelectorAll(".rows"))
     .map(function (box) { return box.scrollWidth - box.clientWidth; }),
    stops: Array.prototype.slice.call(document.querySelectorAll("[tabindex]")).length,
    documentScrollsSideways: document.documentElement.scrollWidth
     - document.documentElement.clientWidth
   };
  })()
 };
}

// Percent escapes decoded the way a browser decodes a javascript: URL, as test-bm.js and
// paste-ready.test.js do it.
function percentDecode(text) {
 return String(text).replace(/(?:%[0-9A-Fa-f]{2})+/g, function (run) {
  try {
   return decodeURIComponent(run);
  } catch (err) {
   var out = "";
   for (var i = 0; i < run.length; i += 3) {
    out += String.fromCharCode(parseInt(run.substr(i + 1, 2), 16));
   }
   return out;
  }
 });
}


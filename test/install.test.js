var wide, tight, narrow, noise, clicked;

test.before(async function () {
 var browser = await playwright.chromium.launch();
 try {
  for (var i = 0; i < WIDTHS.length; i++) {
   var context = await browser.newContext({ viewport: WIDTHS[i] });
   var page = await context.newPage();
   var messages = [], errors = [];
   page.on("console", function (message) {
    if (message.type() === "error" || message.type() === "warning") {
     messages.push(message.type() + ": " + message.text());
    }
   });
   page.on("pageerror", function (err) { errors.push(String(err)); });
   page.on("requestfailed", function (request) {
    errors.push("request failed: " + request.url());
   });
   await serveRoot(page);
   await page.goto(origin + "/install.html", { waitUntil: "load" });
   var read = await page.evaluate(readPage);
   if (i === 0) {
    wide = read;
    noise = { messages: messages.slice(), errors: errors.slice() };
    // One link, clicked where a reader meets it. A javascript: href runs in the page it is on, so
    // the bookmarklet lands on install.html itself, which is a page like any other to it. It is
    // waited for rather than read straight away: this one reads the page before it adds anything.
    var row = wide.rows.filter(function (r) { return r.file === CLICKED + ".js"; })[0];
    await page.locator('a.drag[data-bookmarklet="' + CLICKED + '.js"]').click();
    var waited = null;
    try {
     await page.locator(CLICKED_ADDS).waitFor({ state: "attached", timeout: 5000 });
    } catch (err) {
     waited = String(err).split("\n")[0];
    }
    clicked = {
     added: await page.locator(CLICKED_ADDS).count(),
     waited: waited,
     at: page.url(),
     errors: errors.slice(),
     row: row
    };
   } else if (i === 1) {
    tight = read;
   } else {
    narrow = read;
   }
   await context.close();
  }
 } finally {
  await browser.close();
 }
});

test("the committed install.html is what make-install-page.js writes now", function () {
 var built = maker.build();
 assert.deepStrictEqual(built.problems, [], "the generator found nothing to object to");
 var held = fs.readFileSync(installFile, "utf8");
 assert.strictEqual(held.length, built.text.length, "install.html is " + held.length
  + " characters and the generator writes " + built.text.length
  + ". Run npm run install-page: the committed page is what the site serves, and nothing else "
  + "regenerates it.");
 assert.ok(held === built.text, "install.html differs from what the generator writes, at the same "
  + "length. Run npm run install-page.");
});

test("the page opens quietly, with nothing of its own to log and nothing failing to load",
 function () {
  assert.deepStrictEqual(noise.errors, [], "the page should load every part of itself and throw "
   + "nothing");
  assert.deepStrictEqual(noise.messages, [], "the page carries no script, so it has nothing to say "
   + "to the console");
 });

test("there is a row for every bookmarklet in JSFormatted, and no row for anything else",
 function () {
  var files = names().map(function (n) { return n + ".js"; });
  var onPage = wide.rows.map(function (r) { return r.file; }).sort();
  assert.deepStrictEqual(onPage, files.slice().sort(), "the page should list every file in "
   + "JSFormatted and nothing else");
  assert.strictEqual(wide.rows.length, files.length);
  var counted = wide.tables.reduce(function (sum, t) { return sum + t.rows; }, 0);
  assert.strictEqual(counted, files.length, "every row should be in one of the type tables");
 });

test("each row says what the bookmarklet does and what state it is in", function () {
 var known = ["ready", "changes", "deprecated", "byHand"];
 wide.rows.forEach(function (row) {
  assert.ok(row.title && row.title !== row.file, row.file + ": the row should carry the "
   + "bookmarklet's title as well as its file name, it reads " + JSON.stringify(row.title));
  assert.ok(row.description.length > 10 && row.description.length <= 200, row.file
   + ": the description is " + row.description.length + " characters: "
   + JSON.stringify(row.description));
  assert.ok(!/:$/.test(row.description), row.file + ": the description ends in a colon, so a label "
   + "introducing something the page does not show came with it: "
   + JSON.stringify(row.description));
  assert.ok(known.indexOf(row.statusKind) >= 0, row.file + ": the status reads "
   + JSON.stringify(row.status) + ", which is none of " + known.join(", ")
   + " - the README's navigation list is where it comes from");
 });
});

test("every drag link holds the code test-bm.js ran, character for character", function () {
 var checked = 0;
 wide.rows.forEach(function (row) {
  if (!row.href) { return; }
  var name = row.file.replace(/\.js$/, "");
  assert.ok(/^javascript:/.test(row.href), name + ": the link's address should open javascript:, "
   + "it opens " + row.href.slice(0, 30));
  var ran = percentDecode(row.href.replace(/^javascript:/, ""));
  assert.strictEqual(ran, joinOf(name), name + ": the address a browser would run is not the file "
   + "joined onto one line. What test-bm.js gave a verdict on is that join, so a link holding "
   + "anything else installs code nothing ever ran.");
  var broke = null;
  try { new vm.Script(ran); } catch (err) { broke = err.message; }
  assert.strictEqual(broke, null, name + ": the address a browser would run does not parse: "
   + broke);
  checked++;
 });
 assert.ok(checked > 40, "only " + checked + " links were read, which is too few to be the whole "
  + "list");
});

test("a bookmarklet kept as a record is not offered to install, and every other one is", function () {
 wide.rows.forEach(function (row) {
  if (row.statusKind === "deprecated") {
   assert.strictEqual(row.href, null, row.file + ": it is deprecated, so the page should not hand "
    + "a reader a link to install it");
   assert.ok(/withdrawn/.test(row.noDrag), row.file + ": the row should say why there is no link, "
    + "it says " + JSON.stringify(row.noDrag));
   return;
  }
  assert.ok(row.href, row.file + ": it is " + JSON.stringify(row.status) + ", so it should carry a "
   + "link to drag");
  assert.ok(row.dragText && row.dragText === row.title, row.file + ": the link should be named for "
   + "the bookmarklet, since its name is what the bookmark is saved under, it reads "
   + JSON.stringify(row.dragText));
 });
});

test("each row links the bookmarklet's entry, its gist and its raw file", function () {
 wide.rows.forEach(function (row) {
  var named = row.links.map(function (l) { return l.text; });
  assert.ok(named.indexOf("README") >= 0, row.file + ": no link to its README entry");
  assert.ok(named.indexOf("raw file") >= 0, row.file + ": no link to its raw file");
  row.links.forEach(function (link) {
   assert.ok(/^https:\/\//.test(link.href), row.file + ": the " + link.text + " link is "
    + JSON.stringify(link.href) + ", which is not an address");
   // A README entry with no short of its own keeps the line for one commented out, placeholder
   // address and all. Read with the comments left in, that put
   // https://www.youtube.com/shorts/<id> on the page as a link.
   assert.ok(!/[<>]/.test(link.href), row.file + ": the " + link.text + " link is "
    + JSON.stringify(link.href) + ", which holds a placeholder rather than an address. It has come "
    + "out of a commented-out line in the README entry; the generator takes the comments out "
    + "before it reads one.");
  });
  var raw = row.links.filter(function (l) { return l.text === "raw file"; })[0];
  assert.ok(raw.href.endsWith("/JSFormatted/" + row.file), row.file + ": the raw file link points "
   + "at " + raw.href);
 });
 var withGist = wide.rows.filter(function (row) {
  return row.links.some(function (l) { return l.text === "gist"; });
 });
 assert.strictEqual(withGist.length, wide.rows.length, "every bookmarklet here has a gist, so "
  + "every row should link one; " + (wide.rows.length - withGist.length) + " do not");
});

test("the headings and the tables are built the way a reader is read them out", function () {
 assert.strictEqual(wide.title, "Install a Bookmarklet");
 var levels = wide.headings.map(function (h) { return h.level; });
 assert.strictEqual(levels[0], 1, "the page should open on its h1, it opens on h" + levels[0]);
 levels.forEach(function (level, i) {
  if (i === 0) { return; }
  assert.ok(level <= levels[i - 1] + 1, "the headings skip from h" + levels[i - 1] + " to h" + level
   + " at " + JSON.stringify(wide.headings[i].text));
 });
 wide.tables.forEach(function (table, i) {
  assert.ok(table.caption, "table " + i + " has no caption");
  assert.strictEqual(table.columns.length, 5, "table " + i + " has " + table.columns.length
   + " column headings");
  table.columns.forEach(function (column) {
   assert.strictEqual(column.scope, "col", "table " + i + ": the " + JSON.stringify(column.text)
    + " heading is not scoped to its column");
  });
  assert.ok(table.region, "table " + i + " is not in a box of its own");
 });
});

// The page is five columns wide, so under 760px the rows are laid out as labelled blocks instead.
// What that avoids is the whole page scrolling sideways, which is the defect the practice pages had
// and test/pages.test.js reads for them.
test("the rows stack on a phone, labelled, and the page never scrolls sideways", function () {
 [["wide", wide, WIDE], ["tight", tight, TIGHT]].forEach(function (trio) {
  assert.strictEqual(trio[1].laidOut.rowDisplay, "table-row", "at " + trio[2].width + "px the rows "
   + "should be table rows, they are " + trio[1].laidOut.rowDisplay);
  assert.strictEqual(trio[1].laidOut.headShown, true, "at " + trio[2].width + "px the column "
   + "headings should be shown");
 });
 assert.strictEqual(narrow.laidOut.rowDisplay, "block", "at " + NARROW.width + "px the rows should "
  + "be blocks, they are " + narrow.laidOut.rowDisplay);
 assert.strictEqual(narrow.laidOut.headShown, false, "at " + NARROW.width + "px the column "
  + "headings are laid out as blocks too, so each cell carries its own label and the headings are "
  + "taken out of the flow");
 assert.ok(/What it does/.test(narrow.laidOut.cellLabel || ""), "at " + NARROW.width + "px a cell "
  + "should be labelled from the column it came from, its ::before reads "
  + JSON.stringify(narrow.laidOut.cellLabel));
 [["wide", wide], ["tight", tight], ["narrow", narrow]].forEach(function (pair) {
  assert.ok(pair[1].laidOut.documentScrollsSideways <= 1, "at the " + pair[0] + " width the "
   + "document scrolls " + pair[1].laidOut.documentScrollsSideways + "px sideways, so something in "
   + "it is wider than the viewport. A file name is one unbreakable word and the longest is 52 "
   + "characters; overflow-wrap on it, and the table box laid out as a block under the "
   + "breakpoint, are what hold the page to its width.");
 });
});

// Why none of the five tables is a keyboard stop. A box with nothing to scroll that Tab lands on is
// a stop with nothing to do on it, and the table fits at every width from 320px up - the file names
// break, and under the breakpoint the rows are blocks. overflow-x is the safety net alone: a cell
// that ever did overflow would scroll its own box rather than the page, and the keyboard would then
// want the run-time tabindex the saved pages add. This is the reading that says that day has come.
test("no table has anything to scroll, which is why no box on the page is a keyboard stop",
 function () {
  [["wide", wide, WIDE], ["tight", tight, TIGHT], ["narrow", narrow, NARROW]].forEach(
   function (trio) {
    var scrolls = trio[1].laidOut.boxesScroll;
    assert.strictEqual(scrolls.length, 5, "at " + trio[2].width + "px there should be five table "
     + "boxes, there are " + scrolls.length);
    scrolls.forEach(function (past, i) {
     assert.strictEqual(past, 0, "at " + trio[2].width + "px table box " + i + " holds " + past
      + "px out of view. It is reachable by pointer and by nothing else, since the box is not a "
      + "keyboard stop: give it role=\"region\", a name and a tabindex that is there only while it "
      + "scrolls, the way the saved pages do it, or make the column fit.");
    });
    assert.strictEqual(trio[1].laidOut.stops, 0, "at " + trio[2].width + "px the page carries "
     + trio[1].laidOut.stops + " element(s) with a tabindex, and nothing on it needs one");
   });
 });

test("a link clicked on the page runs the bookmarklet it names", function () {
 assert.ok(clicked.row, CLICKED + " has no row to click");
 assert.strictEqual(clicked.added, 1, "clicking the link for " + CLICKED + " should have put "
  + CLICKED_ADDS + " on the page once, it put it there " + clicked.added + " times"
  + (clicked.waited ? " (" + clicked.waited + ")" : "") + ". The link holds the whole bookmarklet "
  + "as its address, so a click is a reader's own run of it.");
 assert.ok(/\/install\.html$/.test(clicked.at), "the click should have run the bookmarklet on the "
  + "page, not navigated away from it; the page is now " + clicked.at);
 assert.deepStrictEqual(clicked.errors, [], "running it from the page should throw nothing");
});
